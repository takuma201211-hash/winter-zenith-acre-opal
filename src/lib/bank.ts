function shuffle<T>(items: T[]): T[] {
  const next = [...items];
  for (let i = next.length - 1; i > 0; i -= 1) {
    const j = Math.floor(Math.random() * (i + 1));
    const swap = next[i];
    next[i] = next[j]!;
    next[j] = swap!;
  }
  return next;
}

function materialize(item: BankItem): QuizQuestion {
  return {
    id: `bank-${item.id}-${Date.now().toString(36)}`,
    unitId: item.unitId,
    unitTitle: unitTitle(item.unitId),
    kind: item.kind,
    prompt: item.prompt,
    choices: item.kind === "choice" ? shuffle(item.choices) : [],
    answer: item.answer,
    accept: item.accept,
    explanation: item.explanation,
    figure: item.figure,
    source: "bank",
  };
}

export function pickBank(plan: Pick<GenInput, "unitId" | "kind" | "recentPrompts">): QuizQuestion {
  const recent = new Set(plan.recentPrompts);
  const fresh = BANK.filter((item) => !recent.has(item.prompt));
  let pool = fresh.filter((item) => item.unitId === plan.unitId);
  if (plan.kind !== "either") {
    const typed = pool.filter((item) => item.kind === plan.kind);
    if (typed.length > 0) pool = typed;
  }
  if (pool.length === 0) pool = fresh.length > 0 ? fresh : BANK;
  const item = pool[Math.floor(Math.random() * pool.length)] ?? BANK[0]!;
  return materialize(item);
}
